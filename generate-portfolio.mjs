// Lists the real files in public/Portfolio Samples/ and writes src/data/portfolio.generated.js.
// No dependencies. Run from the project root: node scripts/generate-portfolio.mjs
import { readdirSync, openSync, readSync, closeSync, writeFileSync, existsSync } from 'node:fs'
import { join, extname, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { WORK_CATEGORIES } from '../src/data/portfolioCategories.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const base = join(root, 'public', 'Portfolio Samples')
const IMG = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif'])
const VID = new Set(['.mov', '.mp4', '.m4v', '.webm'])

function readHead(path, n = 524288) {
  const fd = openSync(path, 'r')
  const buf = Buffer.alloc(n)
  const got = readSync(fd, buf, 0, n, 0)
  closeSync(fd)
  return buf.subarray(0, got)
}

function exifOrientation(buf, t) {
  const le = buf.toString('latin1', t, t + 2) === 'II'
  const u16 = (o) => (le ? buf.readUInt16LE(o) : buf.readUInt16BE(o))
  const u32 = (o) => (le ? buf.readUInt32LE(o) : buf.readUInt32BE(o))
  const ifd = t + u32(t + 4)
  for (let k = 0, n = u16(ifd); k < n; k++) if (u16(ifd + 2 + k * 12) === 0x0112) return u16(ifd + 2 + k * 12 + 8)
  return 1
}

function imageSize(path) {
  try {
    const buf = readHead(path)
    if (buf.readUInt32BE(0) === 0x89504e47) return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) }
    if (buf[0] !== 0xff || buf[1] !== 0xd8) return null
    let i = 2
    let orient = 1
    while (i + 9 < buf.length) {
      if (buf[i] !== 0xff) { i++; continue }
      const m = buf[i + 1]
      if (m === 0xe1 && buf.toString('latin1', i + 4, i + 8) === 'Exif') orient = exifOrientation(buf, i + 10)
      if (m >= 0xc0 && m <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(m)) {
        let h = buf.readUInt16BE(i + 5)
        let w = buf.readUInt16BE(i + 7)
        if (orient >= 5) [w, h] = [h, w]
        return { w, h }
      }
      i += 2 + buf.readUInt16BE(i + 2)
    }
  } catch { /* fall through */ }
  return null
}

// Looks for codec tags inside a video file. A hint only, not a guarantee.
function videoCodec(path) {
  const found = new Set()
  const fd = openSync(path, 'r')
  const chunk = Buffer.alloc(4 * 1024 * 1024)
  let pos = 0
  let tail = Buffer.alloc(0)
  for (let n; (n = readSync(fd, chunk, 0, chunk.length, pos)) > 0; pos += n) {
    const b = Buffer.concat([tail, chunk.subarray(0, n)])
    if (b.includes('avc1')) found.add('H.264')
    if (b.includes('hvc1') || b.includes('hev1')) found.add('HEVC (H.265)')
    tail = b.subarray(Math.max(0, b.length - 3))
  }
  closeSync(fd)
  return [...found].join(' / ') || null
}

const natural = (a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' })
const out = {}

for (const cat of WORK_CATEGORIES) {
  const dir = join(base, cat.folder)
  if (!existsSync(dir)) {
    console.warn(`MISSING folder: "${cat.folder}". Folders found: ${existsSync(base) ? readdirSync(base).join(' | ') : '(no "Portfolio Samples" folder)'}`)
    out[cat.folder] = []
    continue
  }
  const allowed = cat.kind === 'video' ? VID : IMG
  const names = readdirSync(dir).filter((f) => allowed.has(extname(f).toLowerCase())).sort(natural)
  out[cat.folder] = names.map((file) => {
    if (cat.kind === 'video') return { file, codec: videoCodec(join(dir, file)) }
    const s = imageSize(join(dir, file))
    return s ? { file, w: s.w, h: s.h } : { file }
  })
  const risky = names.filter((f) => /[#?%]/.test(f))
  if (risky.length) console.warn(`   WARNING: rename these (the characters # ? % break file URLs): ${risky.join(', ')}`)
  const skipped = readdirSync(dir).filter((f) => !allowed.has(extname(f).toLowerCase()))
  const note = names.length === cat.expected ? '' : `  <-- expected ${cat.expected}`
  console.log(`${cat.folder}: ${names.length} file(s)${note}${skipped.length ? `  (skipped: ${skipped.join(', ')})` : ''}`)
  if (cat.kind === 'video') out[cat.folder].forEach((v) => console.log(`   ${v.file}: codec hint = ${v.codec ?? 'unknown'}`))
}

const header = '// AUTO-GENERATED by scripts/generate-portfolio.mjs. Do not edit by hand.\n'
writeFileSync(join(root, 'src', 'data', 'portfolio.generated.js'), `${header}export const PORTFOLIO_FILES = ${JSON.stringify(out, null, 2)}\n`)
console.log('Wrote src/data/portfolio.generated.js')
