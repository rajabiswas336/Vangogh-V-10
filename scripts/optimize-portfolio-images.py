# Makes web-sized WebP copies of the images in public/Portfolio Samples/ and
# writes src/data/portfolio.web.generated.js. Originals are never changed.
# Run from the project root after adding images: python scripts/optimize-portfolio-images.py
import json
import shutil
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'public' / 'Portfolio Samples'
OUT = ROOT / 'public' / 'Media' / 'Portfolio' / 'web'
IMG = {'.jpg', '.jpeg', '.png', '.webp'}
MAX_SIDE = 2000
QUALITY = 82

manifest = {}
for path in sorted(SRC.rglob('*')):
    if path.suffix.lower() not in IMG:
        continue
    rel = path.relative_to(SRC)
    target = OUT / rel.with_suffix('.webp')
    kept = target.with_suffix(path.suffix.lower())
    if kept != target and kept.exists() and kept.stat().st_mtime >= path.stat().st_mtime:
        target = kept
    elif not target.exists() or target.stat().st_mtime < path.stat().st_mtime:
        target.parent.mkdir(parents=True, exist_ok=True)
        with Image.open(path) as im:
            im = ImageOps.exif_transpose(im)
            im.thumbnail((MAX_SIDE, MAX_SIDE), Image.LANCZOS)
            if im.mode not in ('RGB', 'RGBA'):
                im = im.convert('RGBA' if 'A' in im.getbands() or 'transparency' in im.info else 'RGB')
            im.save(target, 'WEBP', quality=QUALITY, method=6)
    if target.suffix == '.webp' and target.stat().st_size >= path.stat().st_size:
        # The original is already smaller: ship a copy of it instead of the WebP.
        target.unlink()
        target = target.with_suffix(path.suffix.lower())
        shutil.copy2(path, target)
        print(f'{rel.as_posix()}: original is already smaller, copied as is')
    with Image.open(target) as im:
        w, h = im.size
    manifest[rel.as_posix()] = {'src': '/' + target.relative_to(ROOT / 'public').as_posix(), 'w': w, 'h': h}
    print(f'{rel.as_posix()}: {path.stat().st_size // 1024} KB -> {target.stat().st_size // 1024} KB')

header = '// AUTO-GENERATED by scripts/optimize-portfolio-images.py. Do not edit by hand.\n'
(ROOT / 'src' / 'data' / 'portfolio.web.generated.js').write_text(
    f'{header}export const PORTFOLIO_WEB_IMAGES = {json.dumps(manifest, indent=2, ensure_ascii=False)}\n', encoding='utf-8')
print('Wrote src/data/portfolio.web.generated.js')
